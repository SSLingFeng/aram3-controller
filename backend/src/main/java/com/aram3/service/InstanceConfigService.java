package com.aram3.service;

import com.aram3.common.BusinessException;
import com.aram3.domain.GameInstance;
import com.aram3.repository.AuditRepository;
import com.aram3.repository.InstanceRepository;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Per-instance Arma 3 config files: server.cfg (-config) and basic.cfg (-cfg).
 * Always referenced by absolute path on the start command line.
 */
@Service
public class InstanceConfigService {
    public static final String FILE_SERVER = "server.cfg";
    public static final String FILE_BASIC = "basic.cfg";

    private static final String DEFAULT_SERVER_CFG = """
            // Arma 3 server.cfg — generated by Aram3 Controller
            hostname = "Aram3 Server";
            password = "";
            passwordAdmin = "";
            maxPlayers = 32;
            // BattlEye = 1;
            // verifySignatures = 2;
            // voteThreshold = 0.51;
            // kickDuplicate = 1;
            // allowedFilePatching = 2;
            """;

    private static final String DEFAULT_BASIC_CFG = """
            // Arma 3 basic.cfg — generated by Aram3 Controller
            // MaxMsgSend = 128;
            // MaxSizeGuaranteed = 512;
            // MaxSizeNonguaranteed = 256;
            // MinErrorToSend = 0.001;
            // MinErrorToSendNear = 0.01;
            // MaxCustomFileSize = 0;
            // Windowed = 0;
            """;

    private final InstanceRepository instanceRepository;
    private final AuditRepository auditRepository;

    public InstanceConfigService(InstanceRepository instanceRepository, AuditRepository auditRepository) {
        this.instanceRepository = instanceRepository;
        this.auditRepository = auditRepository;
    }

    public Path serverCfgPath(GameInstance inst) {
        return Path.of(inst.rootPath()).resolve(FILE_SERVER).toAbsolutePath().normalize();
    }

    public Path basicCfgPath(GameInstance inst) {
        return Path.of(inst.rootPath()).resolve(FILE_BASIC).toAbsolutePath().normalize();
    }

    public void ensureDefaultConfigs(GameInstance inst) {
        writeFileIfAbsent(serverCfgPath(inst), DEFAULT_SERVER_CFG);
        writeFileIfAbsent(basicCfgPath(inst), DEFAULT_BASIC_CFG);
    }

    public Map<String, Object> read(long instanceId) {
        GameInstance inst = require(instanceId);
        ensureDefaultConfigs(inst);
        Map<String, Object> body = new LinkedHashMap<>();
        body.put("instanceId", inst.id());
        body.put("instanceCode", inst.code());
        body.put("serverCfgPath", serverCfgPath(inst).toString());
        body.put("basicCfgPath", basicCfgPath(inst).toString());
        body.put("serverCfg", readFile(serverCfgPath(inst)));
        body.put("basicCfg", readFile(basicCfgPath(inst)));
        return body;
    }

    public Map<String, Object> save(long instanceId, String serverCfg, String basicCfg) {
        GameInstance inst = require(instanceId);
        ensureDefaultConfigs(inst);
        if (serverCfg != null) {
            writeFile(serverCfgPath(inst), serverCfg);
        }
        if (basicCfg != null) {
            writeFile(basicCfgPath(inst), basicCfg);
        }
        auditRepository.log(null, "instance.config.save", "instance", instanceId,
                "server=" + (serverCfg != null) + ",basic=" + (basicCfg != null), null);
        return read(instanceId);
    }

    public Map<String, Object> reset(long instanceId) {
        GameInstance inst = require(instanceId);
        writeFile(serverCfgPath(inst), DEFAULT_SERVER_CFG);
        writeFile(basicCfgPath(inst), DEFAULT_BASIC_CFG);
        auditRepository.log(null, "instance.config.reset", "instance", instanceId, null, null);
        return read(instanceId);
    }

    private GameInstance require(long instanceId) {
        return instanceRepository.findById(instanceId)
                .orElseThrow(() -> new BusinessException("实例不存在"));
    }

    private void writeFileIfAbsent(Path path, String content) {
        try {
            Files.createDirectories(path.getParent());
            if (!Files.exists(path)) {
                Files.writeString(path, content, StandardCharsets.UTF_8);
            }
        } catch (IOException e) {
            throw new BusinessException("创建配置文件失败: " + path + " / " + e.getMessage());
        }
    }

    private void writeFile(Path path, String content) {
        try {
            Files.createDirectories(path.getParent());
            Files.writeString(path, content == null ? "" : content, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new BusinessException("写入配置失败: " + path + " / " + e.getMessage());
        }
    }

    private String readFile(Path path) {
        try {
            if (!Files.exists(path)) {
                return "";
            }
            return Files.readString(path, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new BusinessException("读取配置失败: " + path + " / " + e.getMessage());
        }
    }
}
